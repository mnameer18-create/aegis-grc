begin;

create table if not exists public.business_units (
  id uuid primary key default gen_random_uuid(),
  code text not null unique,
  name text not null,
  description text,
  parent_business_unit_id uuid references public.business_units(id),
  head_user_id uuid,
  compliance_contact_user_id uuid,
  is_active boolean not null default true,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists business_units_active_idx
  on public.business_units(is_active, name);

alter table public.internal_documents
  add column if not exists owner_business_unit_id uuid references public.business_units(id);

alter table public.gap_assessments
  add column if not exists business_unit_id uuid references public.business_units(id);

alter table public.remediation_actions
  add column if not exists owner_business_unit_id uuid references public.business_units(id);

alter table public.cet_assessments
  add column if not exists business_unit_id uuid references public.business_units(id);

create table if not exists public.workflow_approval_steps (
  id uuid primary key default gen_random_uuid(),
  workflow_definition_id uuid not null references public.workflow_definitions(id) on delete cascade,
  step_key text not null,
  step_name text not null,
  step_order integer not null,
  approver_type text not null default 'role',
  approver_role text,
  approver_user_id uuid,
  approver_business_unit_id uuid references public.business_units(id),
  minimum_approvals integer not null default 1,
  conditions jsonb not null default '{}'::jsonb,
  can_return boolean not null default true,
  can_reject boolean not null default true,
  can_delegate boolean not null default false,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(workflow_definition_id, step_key),
  unique(workflow_definition_id, step_order),
  check (step_order > 0),
  check (minimum_approvals > 0),
  check (approver_type in ('role','user','business_unit','dynamic'))
);

create index if not exists workflow_approval_steps_order_idx
  on public.workflow_approval_steps(workflow_definition_id, step_order);

create table if not exists public.escalation_rules (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  module_key text not null,
  entity_type text not null,
  trigger_type text not null,
  trigger_offset_days integer,
  escalation_level integer not null default 1,
  recipient_type text not null default 'role',
  recipient_role text,
  recipient_user_id uuid,
  recipient_business_unit_id uuid references public.business_units(id),
  channel text not null default 'in_app',
  repeat_interval_hours integer,
  max_repeats integer,
  conditions jsonb not null default '{}'::jsonb,
  message_template text,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  created_by uuid,
  check (escalation_level >= 0),
  check (trigger_type in ('before_due','on_due','overdue','status_stalled','evidence_pending','review_pending')),
  check (recipient_type in ('role','user','business_unit','entity_owner','manager')),
  check (channel in ('in_app','email','webhook'))
);

create index if not exists escalation_rules_lookup_idx
  on public.escalation_rules(module_key, entity_type, trigger_type, is_active);

create table if not exists public.workflow_step_events (
  id bigint generated by default as identity primary key,
  workflow_instance_id uuid not null references public.workflow_instances(id) on delete cascade,
  approval_step_id uuid references public.workflow_approval_steps(id),
  event_type text not null,
  actor_user_id uuid,
  comment text,
  payload jsonb not null default '{}'::jsonb,
  occurred_at timestamptz not null default now(),
  check (event_type in ('entered','submitted','approved','returned','rejected','delegated','skipped','completed'))
);

create index if not exists workflow_step_events_instance_idx
  on public.workflow_step_events(workflow_instance_id, occurred_at);

alter table public.business_units enable row level security;
alter table public.workflow_approval_steps enable row level security;
alter table public.escalation_rules enable row level security;
alter table public.workflow_step_events enable row level security;

revoke all on public.business_units from anon, authenticated;
revoke all on public.workflow_approval_steps from anon, authenticated;
revoke all on public.escalation_rules from anon, authenticated;
revoke all on public.workflow_step_events from anon, authenticated;

grant select, insert, update, delete on public.business_units to service_role;
grant select, insert, update, delete on public.workflow_approval_steps to service_role;
grant select, insert, update, delete on public.escalation_rules to service_role;
grant select, insert, update, delete on public.workflow_step_events to service_role;
grant usage, select on all sequences in schema public to service_role;

comment on table public.business_units is
  'Noventra Business Unit master used by compliance assessments, remediation, CET and workflow routing.';

comment on table public.workflow_approval_steps is
  'Configurable ordered approval steps attached to a versioned Noventra workflow definition.';

comment on table public.escalation_rules is
  'Configurable reminder and escalation rules evaluated by scheduled workflow automation.';

comment on table public.workflow_step_events is
  'Immutable workflow decision/event history used for approval traceability.';

commit;
