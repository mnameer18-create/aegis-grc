-- AEGIS Phase 3 RAG MVP
-- Supabase / Postgres schema for regulatory document retrieval
-- Run in Supabase SQL Editor as project owner.

create extension if not exists vector with schema extensions;

create table if not exists public.regulatory_documents (
  id uuid primary key default gen_random_uuid(),
  title text not null,
  source_org text not null,
  source_type text not null default 'regulatory_document',
  source_url text,
  version_label text,
  effective_date date,
  jurisdiction text not null default 'Malaysia',
  status text not null default 'active',
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.regulatory_chunks (
  id bigint generated by default as identity primary key,
  document_id uuid not null references public.regulatory_documents(id) on delete cascade,
  chunk_index integer not null,
  page_number integer,
  section_title text,
  content text not null,
  token_estimate integer,
  embedding extensions.vector(1536) not null,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  unique(document_id, chunk_index)
);

create index if not exists regulatory_chunks_document_id_idx
  on public.regulatory_chunks(document_id);

create index if not exists regulatory_chunks_embedding_hnsw_idx
  on public.regulatory_chunks
  using hnsw (embedding extensions.vector_cosine_ops);

alter table public.regulatory_documents enable row level security;
alter table public.regulatory_chunks enable row level security;

-- No anon/authenticated table policies are created on purpose.
-- Phase 3 MVP reads/writes through protected server-side workflows using
-- a Supabase secret/service credential. The browser never receives that key.

create or replace function public.match_regulatory_chunks(
  query_embedding extensions.vector(1536),
  match_count integer default 6,
  min_similarity double precision default 0.55,
  filter_document_ids uuid[] default null
)
returns table (
  chunk_id bigint,
  document_id uuid,
  document_title text,
  source_org text,
  source_url text,
  version_label text,
  effective_date date,
  chunk_index integer,
  page_number integer,
  section_title text,
  content text,
  similarity double precision
)
language sql
stable
security invoker
set search_path = public, extensions
as $$
  select
    c.id as chunk_id,
    d.id as document_id,
    d.title as document_title,
    d.source_org,
    d.source_url,
    d.version_label,
    d.effective_date,
    c.chunk_index,
    c.page_number,
    c.section_title,
    c.content,
    1 - (c.embedding <=> query_embedding) as similarity
  from public.regulatory_chunks c
  join public.regulatory_documents d on d.id = c.document_id
  where
    d.status = 'active'
    and (filter_document_ids is null or c.document_id = any(filter_document_ids))
    and 1 - (c.embedding <=> query_embedding) >= min_similarity
  order by c.embedding <=> query_embedding
  limit greatest(1, least(match_count, 20));
$$;

revoke all on function public.match_regulatory_chunks(
  extensions.vector, integer, double precision, uuid[]
) from public, anon, authenticated;

grant execute on function public.match_regulatory_chunks(
  extensions.vector, integer, double precision, uuid[]
) to service_role;

comment on table public.regulatory_documents is
  'AEGIS authoritative-source metadata for Phase 3 regulatory RAG.';

comment on table public.regulatory_chunks is
  'AEGIS source text chunks and embeddings. Do not expose directly to browser clients.';
